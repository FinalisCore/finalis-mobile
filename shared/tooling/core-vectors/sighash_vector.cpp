// Emits a P2PKH sighash/signing vector computed by finalis-core itself.
#include <cstdio>
#include <iostream>
#include <string>

#include "common/address.hpp"
#include "common/types.hpp"
#include "crypto/ed25519.hpp"
#include "crypto/hash.hpp"
#include "utxo/tx.hpp"
#include "utxo/validate.hpp"

using namespace finalis;

static Hash32 fill32(std::uint8_t start) {
  Hash32 h{};
  for (int i = 0; i < 32; ++i) h[i] = static_cast<std::uint8_t>(start + i);
  return h;
}

int main() {
  const std::string network_id_hex = "a6ffe3b32f81d1ad7df761693dc87dd8";
  const std::string genesis_hash_hex = "4faa7e1b8e79509c767f7f51f711eba7c75e9e9e4d9ea105fa020dd15cdd9d0c";
  const auto domain = chain_domain_from_hex(network_id_hex, genesis_hash_hex);
  if (!domain) return 1;

  std::array<std::uint8_t, 32> seed{};
  for (int i = 0; i < 32; ++i) seed[i] = static_cast<std::uint8_t>(i + 1);
  const auto kp = crypto::keypair_from_seed32(seed);
  if (!kp) return 1;
  const auto pkh = crypto::h160(Bytes(kp->public_key.begin(), kp->public_key.end()));
  const auto sender = address::encode_p2pkh("tsc", pkh);

  std::array<std::uint8_t, 20> recipient_pkh{};
  for (int i = 0; i < 20; ++i) recipient_pkh[i] = static_cast<std::uint8_t>(0xa0 + i);
  const auto recipient = address::encode_p2pkh("tsc", recipient_pkh);

  Tx tx;
  tx.version = 1;
  tx.lock_time = 0;
  tx.inputs.push_back(TxIn{fill32(0x10), 0, {}, 0xFFFFFFFF});
  tx.inputs.push_back(TxIn{fill32(0x40), 3, {}, 0xFFFFFFFF});
  tx.outputs.push_back(TxOut{150'000, address::p2pkh_script_pubkey(recipient_pkh)});
  tx.outputs.push_back(TxOut{48'000, address::p2pkh_script_pubkey(pkh)});

  const Tx unsigned_tx = tx;
  std::string sighashes[2];
  for (std::uint32_t i = 0; i < tx.inputs.size(); ++i) {
    const auto msg = signing_message_for_input(*domain, unsigned_tx, i);
    if (!msg) return 1;
    sighashes[i] = hex_encode(*msg);
    const auto sig = crypto::ed25519_sign(*msg, kp->private_key);
    if (!sig) return 1;
    Bytes ss;
    ss.push_back(0x40);
    ss.insert(ss.end(), sig->begin(), sig->end());
    ss.push_back(0x20);
    ss.insert(ss.end(), kp->public_key.begin(), kp->public_key.end());
    tx.inputs[i].script_sig = ss;
  }

  // Length >= 0x80 exercises the multi-byte ULEB128 varint path.
  Tx long_script;
  long_script.inputs.push_back(TxIn{fill32(0x01), 1, Bytes(200, 0xab), 0xFFFFFFFF});
  long_script.outputs.push_back(TxOut{1, Bytes(300, 0xcd)});

  std::cout << "{\n"
            << "  \"description\": \"Generated by finalis-core (signing_message_for_input, chain_domain_from_hex, Tx::serialize). Do not edit by hand.\",\n"
            << "  \"network_name\": \"testnet\",\n"
            << "  \"network_id_hex\": \"" << network_id_hex << "\",\n"
            << "  \"genesis_hash_hex\": \"" << genesis_hash_hex << "\",\n"
            << "  \"chain_domain_hex\": \"" << hex_encode32(*domain) << "\",\n"
            << "  \"private_key_hex\": \"" << hex_encode(Bytes(seed.begin(), seed.end())) << "\",\n"
            << "  \"public_key_hex\": \"" << hex_encode(Bytes(kp->public_key.begin(), kp->public_key.end())) << "\",\n"
            << "  \"sender_address\": \"" << *sender << "\",\n"
            << "  \"recipient_address\": \"" << *recipient << "\",\n"
            << "  \"unsigned_tx_hex\": \"" << hex_encode(unsigned_tx.serialize_without_hashcash()) << "\",\n"
            << "  \"sighash_input_0_hex\": \"" << sighashes[0] << "\",\n"
            << "  \"sighash_input_1_hex\": \"" << sighashes[1] << "\",\n"
            << "  \"signed_tx_hex\": \"" << hex_encode(tx.serialize()) << "\",\n"
            << "  \"signed_txid_hex\": \"" << hex_encode32(tx.txid()) << "\",\n"
            << "  \"long_script_tx_hex\": \"" << hex_encode(long_script.serialize()) << "\"\n"
            << "}\n";
  return 0;
}
